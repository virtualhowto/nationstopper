/* Nation Stopper — interface layer.
   UI-only presentation. The original game engine remains authoritative. */
(function(){
  "use strict";
  const game=window.NationStopperGame;
  if(!game || !game.state) return;
  const S=game.state;
  const get=id=>document.getElementById(id);
  const horse=get("horseSelect");
  const gate=get("gateHorseSelect");
  const board=get("leaderboard");
  const topButton=get("boardTop");
  const allButton=get("boardAll");
  const findButton=get("boardFind");
  const liveCard=get("liveRaceCard");
  const liveList=get("liveTopThree");
  const callout=get("playerCallout");
  const progress=get("courseProgress");
  const marker=get("courseMarker");
  const title=get("courseStage");
  const strategy=get("courseStrategy");
  const percent=get("coursePercent");
  const pauseOverlay=get("pauseOverlay");
  const pace=get("paceValue");
  const stage=get("stageWrap");
  if(!horse||!gate||!board) return;

  // Keep the in-gate quick picker and the original full runner selector in sync.
  function mirrorPicker(){
    gate.replaceChildren();
    for(const option of horse.options){
      const copy=document.createElement("option");
      copy.value=option.value;
      copy.textContent=option.textContent;
      gate.appendChild(copy);
    }
    gate.value=horse.value;
  }
  mirrorPicker();
  gate.addEventListener("change",()=>{
    horse.value=gate.value;
    horse.dispatchEvent(new Event("change",{bubbles:true}));
  });
  horse.addEventListener("change",()=>{gate.value=horse.value;});
  get("resumeButton")?.addEventListener("click",()=>get("pauseButton")?.click());

  // The board remains sorted and generated by game.js. Filtering only changes
  // its presentation and never changes the simulation.
  let view="all";
  function chooseBoard(next){
    view=next;
    board.classList.toggle("is-top-eight",view==="top");
    allButton.classList.toggle("is-selected",view==="all");
    topButton.classList.toggle("is-selected",view==="top");
    allButton.setAttribute("aria-pressed",String(view==="all"));
    topButton.setAttribute("aria-pressed",String(view==="top"));
  }
  allButton?.addEventListener("click",()=>chooseBoard("all"));
  topButton?.addEventListener("click",()=>chooseBoard("top"));
  findButton?.addEventListener("click",()=>{
    chooseBoard("all");
    requestAnimationFrame(()=>board.querySelector("li.player")?.scrollIntoView({block:"nearest",behavior:"smooth"}));
  });

  const esc=s=>String(s).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
  function ordered(){
    return S.horses.slice().sort((a,b)=>{
      if(a.finishedAt!=null) return b.finishedAt!=null ? a.finishedAt-b.finishedAt : -1;
      return b.finishedAt!=null ? 1 : b.progress-a.progress;
    });
  }

  let previousMode="",previousTop="",previousPace="",previousStage="";
  function update(){
    const mode=S.phase;
    if(mode!==previousMode){
      document.body.dataset.raceMode=mode;
      stage.dataset.raceMode=mode;
      previousMode=mode;
    }
    gate.disabled=mode!=="menu";
    const running=mode==="race"||mode==="finish";
    const fraction=S.player?Math.max(0,Math.min(1,S.player.progress/3200)):0;
    const pct=Math.min(100,Math.round(fraction*100));
    progress.style.width=pct+"%";
    marker.style.left=pct+"%";
    percent.textContent=pct+"% COMPLETE";
    let label="AT THE GATES",tip="Pick your mount and line up for the start.";
    if(mode==="count"){label="THE COUNTDOWN";tip="Steady on. The gates are about to open.";}
    else if(mode==="finish"){label="RACE COMPLETE";tip="The official game result is in.";}
    else if(mode==="race"){
      if(fraction<.19){label="THE OPENING RUN";tip="Find a lane and avoid spending all your stamina.";}
      else if(fraction<.5){label="SETTLE INTO STRIDE";tip="Ease your horse and keep something in reserve.";}
      else if(fraction<.75){label="THE BACK STRAIGHT";tip="Position for the run home.";}
      else if(fraction<.89){label="THE FINAL BEND";tip="Move into daylight before the straight.";}
      else{label="THE HOME STRAIGHT";tip="The finish is near. Give your mount everything left.";}
      if(S.stamina<.2 && S.elapsed>=S.kickUntil){tip="Low stamina: release RIDE to recover.";}
      else if(S.focus>=.98 && fraction>.72){tip="Finishing kick ready — press SHIFT or tap KICK!";}
      else if(S.position>12 && fraction>.7){tip="You are behind. Find clear ground and push on.";}
    }
    if(previousStage!==label+"|"+tip){title.textContent=label;strategy.textContent=tip;previousStage=label+"|"+tip;}
    let paceLabel="SETTLED";
    if(mode==="race"){
      if(S.elapsed<S.kickUntil)paceLabel="⚡ KICKING";
      else if(S.ride)paceLabel="PUSHING";
      else if(S.stamina<.95)paceLabel="RECOVERING";
    }
    if(paceLabel!==previousPace){pace.textContent=paceLabel;previousPace=paceLabel;}
    if(running && S.horses.length){
      const ranked=ordered();
      const signature=ranked.slice(0,3).map(h=>h.no).join(",");
      if(signature!==previousTop){
        liveList.innerHTML=ranked.slice(0,3).map((h,index)=>'<div class="live-top-row"><span class="live-top-pos">'+(index+1)+'</span><span class="live-top-swatch" style="background:'+h.silk+'"></span><span class="live-top-name" title="'+esc(h.name)+'">'+esc(h.name)+'</span></div>').join("");
        previousTop=signature;
      }
      callout.innerHTML="YOUR MOUNT <strong>"+S.player.no+" · "+esc(S.player.name)+" / "+S.position+" OF 24</strong>";
    } else previousTop="";
    liveCard.hidden=mode!=="race" || S.paused;
    pauseOverlay.hidden=!S.paused || (mode!=="race"&&mode!=="count");
  }
  update();
  window.setInterval(update,160);
})();